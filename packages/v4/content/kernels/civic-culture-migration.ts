import type { EventEffect, Relation, RoleRequirement } from '../../domain.js';
import type { GeneratedTaskMeta } from '../../generated.js';
import type { PlotKernel } from '../../composition/types.js';

/**
 * Phase 11 civic, cultural and migration kernels.
 *
 * These are causal mechanisms, not a fixed calendar. The composer binds each
 * kernel to a context and a milieu; every outcome writes engine state that can
 * be inspected later. War, crisis, reform and postwar variants require an
 * active process or legacy, never a particular year.
 */

const subjectRole = (min: number, max: number): RoleRequirement => ({
  key: 'subject',
  kind: 'subject',
  required: true,
  minAge: min,
  maxAge: max,
});

const cast = (
  key: string,
  kind: RoleRequirement['kind'],
  extra: Partial<RoleRequirement> = {},
): RoleRequirement => ({ key, kind, required: true, ...extra });

const taskMeta = (
  domain: GeneratedTaskMeta['domain'],
  goals: string[],
  needs: string[],
  baseUtility: number,
  risk: number,
  skills: string[] = [],
): GeneratedTaskMeta => ({ domain, goals, needs, baseUtility, risk, skills });

const cash = (amount: number, reason: string): EventEffect => ({
  type: 'cash',
  householdId: '$household',
  amount,
  reason,
});

const flag = (name: string, reason: string): EventEffect => ({
  type: 'flag',
  personId: '$subject',
  flag: name,
  add: true,
  reason,
});

const reputation = (amount: number, reason: string): EventEffect => ({
  type: 'reputation',
  personId: '$subject',
  amount,
  reason,
});

const health = (amount: number, reason: string): EventEffect => ({
  type: 'health',
  personId: '$subject',
  amount,
  reason,
});

const know = (
  proposition: string,
  confidence: number,
  sourceKind: 'witnessed' | 'told' | 'document' | 'inferred' = 'witnessed',
  personId?: string,
  visibility: 'private' | 'shared' = 'private',
): EventEffect => ({
  type: 'knowledge',
  holderId: '$subject',
  proposition,
  confidence,
  sourceKind,
  ...(personId ? { personId } : {}),
  visibility,
  trueInWorld: true,
});

const link = (
  key: string,
  kind: Relation['kind'],
  values: Partial<Pick<Relation, 'trust' | 'affection' | 'obligation' | 'fear' | 'respect'>>,
  reason: string,
): EventEffect => ({
  type: 'relation',
  a: '$subject',
  b: `$${key}`,
  kind,
  ...values,
  reason,
});

const unlink = (key: string, kind: Relation['kind'], reason: string): EventEffect => ({
  type: 'relation_end',
  a: '$subject',
  b: `$${key}`,
  kind,
  reason,
});

const role = (name: string, reason: string): EventEffect => ({
  type: 'role',
  personId: '$subject',
  role: name,
  add: true,
  reason,
});

const membership = (organizationId: string, reason: string): EventEffect => ({
  type: 'organization_membership',
  personId: '$subject',
  organizationId,
  add: true,
  reason,
});

const condition = (name: string, reason: string): EventEffect => ({
  type: 'condition',
  personId: '$subject',
  condition: name,
  add: true,
  reason,
});

const move = (locationId: string, reason: string): EventEffect => ({
  type: 'move',
  personId: '$subject',
  locationId,
  reason,
});

const moveOther = (personId: string, locationId: string, reason: string): EventEffect => ({
  type: 'move',
  personId,
  locationId,
  reason,
});

const residence = (residenceId: string, reason: string): EventEffect => ({
  type: 'residence',
  householdId: '$household',
  residenceId,
  reason,
});

const employment = (
  organizationId: string,
  occupation: string,
  wage: number,
  workplaceId: string,
  reason: string,
): EventEffect => ({
  type: 'employment',
  personId: '$subject',
  organizationId,
  occupation,
  wage,
  workplaceId,
  reason,
});

const unemployment = (reason: string): EventEffect => ({
  type: 'unemployment',
  personId: '$subject',
  reason,
});

