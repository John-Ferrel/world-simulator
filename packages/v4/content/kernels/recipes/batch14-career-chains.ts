/**
 * Follow-up targets point only at event kernels: the engine's scheduled-event
 * resolver deliberately skips task definitions. The tasks in this batch are
 * therefore made available by the same history tags as choices, not queued as
 * deferred scenes. That keeps every queued follow-up an event that can commit.
 */

type RememberedOptions = {
  minAge?: number;
  maxAge?: number;
  required?: boolean;
  occupation?: string;
};

/** A role that must be an actual person from the subject's past. */
function remembered(
  kind: RoleRequirement['kind'],
  tag: string,
  options: RememberedOptions = {},
): RoleDecl {
  return [kind, { ...options, sharedHistoryTag: tag }] as unknown as RoleDecl;
}

