/**
 * Phase 14 · historical participation that persists.
 *
 * A strike vote, a mobilization poster, an arrest at dawn, a requisition list
 * or a hiding place is not a mood: it writes a flag, a role, a relation or a
 * body condition, and later scenes read that committed history. Returning
 * people are cast through `sharedHistoryTag`, so the old foreman, cellmate,
 * comrade or denounced neighbor is the person who was actually there.
 */

/** `sharedHistoryTag` is a domain role field not yet mirrored in the kit tuple. */
function sharedRole(
  kind: RoleRequirement['kind'],
  tag: string,
  options: { minAge?: number; maxAge?: number; required?: boolean } = {},
): RoleDecl {
  return [kind, { ...options, sharedHistoryTag: tag }] as unknown as RoleDecl;
}

